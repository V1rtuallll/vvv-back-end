-- =============================================================================
-- V004 — about_page 删掉身份两列
-- =============================================================================
--
-- 做了什么
-- --------
--   删除 about_page.avatar_src 与 about_page.display_name。
--
-- 为什么
-- ------
--   About 页面的头像与昵称改为直接读站点账号（user 表 id = 0）的实时值，
--   这两列不再有任何写入方。留着它们会让实体字段、Mapper 的 NULL 分支和契约测试
--   都围着两个死列转，而且这张表存的东西不再等于「用户真正在编辑的东西」。
--
--   取舍：以后若要给 About 页单独设一个昵称，需要再加回来。
--
-- 兼容性
-- ------
--   ALTER TABLE ... DROP COLUMN 在 MySQL 5.6 与 8.x 上都可用。
--   两列都可空、无默认值、未被任何索引引用，删除不影响其它结构。
--
-- 不往 schema_migrations 写记录：db/migrate.sh 会写。
-- 本文件执行过一次之后不要修改（运行器锁 SHA-256）。
-- =============================================================================

ALTER TABLE `about_page`
  DROP COLUMN `avatar_src`,
  DROP COLUMN `display_name`;
