-- =============================================================================
-- V007 — 背景音乐的显示名
-- =============================================================================
--
-- 做了什么
-- --------
--   给 gallery_bgm_media 加一列 title：上传这个 OSS 对象时文件的原始名。
--
-- 为什么
-- ------
--   Gallery 详情要显示「现在放的是哪一首」。名字有两个来源，按优先级：
--
--     1. 地址命中了某条 gallery 行 → 用那条项的 title（曲子本来就是画廊资源）；
--     2. 否则用 gallery_bgm_media.title（经「上传新文件」进来的曲子）。
--
--   第 2 条以前没有落脚点：登记表只有 url / object_key / uploader_id。而 object_key
--   是 `music/<UUID>.mp3`（见 OssUtil.upload），从地址反推只能得到一串认不出的字符。
--   原始文件名在「上传的那一刻」还拿得到，错过就永久丢了 —— 所以这一列只能在上传
--   时写入，事后补不回来。这也决定了**已有的行填不上**，它们的 title 是 NULL，
--   详情退化成只显示类型。
--
--   列名用 title 与 gallery.title 对齐：对用户来说两者是同一件事（这条资源叫什么），
--   填法也沿用同一条既有约定 —— 上传时标题留空就用文件名兜底。
--
-- 顺序
-- ----
--   先执行本脚本，再发布后端。旧代码不引用新列，所以「旧代码 + 新结构」是安全的；
--   反过来「新代码 + 旧结构」会让画廊列表直接失败（新代码要读这一列）。
--
-- 不往 schema_migrations 写记录：db/migrate.sh 会写。
-- 本文件执行过一次之后不要修改（运行器锁 SHA-256）。
-- =============================================================================

ALTER TABLE `gallery_bgm_media`
  ADD COLUMN `title` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL
    COMMENT '上传时的原始文件名，仅用于显示' AFTER `object_key`;

